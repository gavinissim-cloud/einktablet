let lang = "en";
try {
  if (localStorage.getItem("hw_lang") === "he") lang = "he";
} catch {}

/** Text for `key` in the current language, with {name} placeholders filled. */
function t(key, vars = {}) {
  const s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

/** A readable message for an error from the server or the preview backend. */
function errText(err) {
  const key = err?.code && `err.${err.code}`;
  return key && (STRINGS[lang][key] || STRINGS.en[key]) ? t(key) : err?.message || String(err);
}

/** Apply the language to the page's fixed text (elements marked data-i18n*). */
function applyLanguage() {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "he" ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
}

function setLanguage(next) {
  lang = next;
  try { localStorage.setItem("hw_lang", next); } catch {}
  applyLanguage();
}
