import { launch, makePage, tagCrops, installFake, checker, dbDump } from "./harness.mjs";
const [S, NEW, OLD] = process.argv.slice(2);
const { browser, ctx } = await launch();
const { check, done } = checker();
const errors = [];
// 1. the old version makes data
let page = await ctx.newPage();
page.on("pageerror", (e) => errors.push("old: " + e.message));
await page.goto("file://" + OLD);
let truth = await makePage(page, `${S}/e2e/page.png`);
await tagCrops(page);
await installFake(page, truth);
await page.fill("#keyInput", "AQ.k"); await page.click("#keySave");
await page.setInputFiles("#fileInput", `${S}/e2e/page.png`);
await page.waitForSelector(".dialog input"); await page.fill(".dialog input", "Old person"); await page.click(".dialog button[type=submit]");
await page.waitForFunction(() => /lines/.test(document.querySelector(".page-head .state")?.textContent || ""), null, { timeout: 120000 });
await page.locator(".row textarea").nth(2).fill("תיקון בגרסה הישנה");
await page.waitForTimeout(1500);
const oldDb = await dbDump(page);
check("old version stored an example (old id format)", oldDb.writers[0].examples.length === 1 && /:\d+$/.test(oldDb.writers[0].examples[0].id), JSON.stringify(oldDb.writers[0].examples.map((e) => e.id)));
await page.close();
// 2. the new version opens the same data
page = await ctx.newPage();
page.on("pageerror", (e) => errors.push("new: " + e.stack));
page.on("console", (m) => { if (m.type() === "error") errors.push("new console: " + m.text()); });
await page.goto("file://" + NEW);
await tagCrops(page);
await installFake(page, truth);
await page.waitForSelector("#home:not([hidden])");
check("old documents listed", (await page.locator("#docList a").count()) === 1);
await page.locator("#docList a").first().click();
await page.waitForSelector(".row textarea");
check("old document opens with its edit", (await page.locator(".row textarea").nth(2).inputValue()) === "תיקון בגרסה הישנה");
await page.locator(".row textarea").nth(3).fill("תיקון בגרסה החדשה");
await page.waitForTimeout(1500);
let db = await dbDump(page);
check("old example converted, new one added, no duplicates", db.writers[0].examples.length === 2 && db.writers[0].examples.every((e) => !/:\d+$/.test(e.id)), db.writers[0].examples.map((e) => e.id).join(", "));
await page.click("#viewDoc"); await page.waitForSelector(".doc");
await page.click("#viewLines"); await page.waitForSelector(".row textarea");
await page.selectOption("#writerSelect", "__new"); await page.fill(".dialog input", "New person"); await page.click(".dialog button[type=submit]");
await page.waitForTimeout(1500);
db = await dbDump(page);
const np = db.writers.find((w) => w.name === "New person");
check("switching person moves the learning", np && np.examples.length >= 1, JSON.stringify(db.writers.map((w) => [w.name, w.examples.length])));
await page.locator(".page-head button", { hasText: "Read again" }).click(); await page.click(".dialog button[type=submit]");
await page.waitForFunction(() => /lines/.test(document.querySelector(".page-head .state")?.textContent || ""), null, { timeout: 120000 });
await page.click("#backHome");
await page.locator("#writerList a", { hasText: "New person" }).click();
await page.waitForSelector("#writerView:not([hidden])");
await page.locator(".example button", { hasText: "Forget" }).first().click();
await page.waitForTimeout(500);
check("no errors with old data", errors.length === 0, errors.join("\n"));
await browser.close();
process.exit(done() ? 0 : 1);
