import { start, makePage, tagCrops, installFake, checker, TRUTH } from "./harness.mjs";
import fs from "node:fs";
const [S, FILE] = process.argv.slice(2);
const { browser, ctx, page, errors } = await start(FILE);
await ctx.grantPermissions(["clipboard-read", "clipboard-write"]);
const { check, done } = checker();
const truth = await makePage(page, `${S}/e2e/page.png`);
await tagCrops(page);
await installFake(page, truth);
await page.fill("#keyInput", "AQ.k"); await page.click("#keySave");
await page.setInputFiles("#fileInput", [`${S}/e2e/p1.png`, `${S}/e2e/p2.png`]);
await page.waitForSelector(".dialog input"); await page.fill(".dialog input", "T"); await page.click(".dialog button[type=submit]");
await page.waitForFunction(() => [...document.querySelectorAll(".page-head .state")].filter((s) => s.textContent.includes("lines")).length === 2, null, { timeout: 120000 });
// a line with characters that are invalid in a Word file, and XML-special characters
await page.locator(".row textarea").first().fill("בדיקה <a> & \"x\" \u0001\u000b סוף");
await page.waitForTimeout(1200);
const get = async (sel, name) => { const [dl] = await Promise.all([page.waitForEvent("download"), page.click(sel)]); await dl.saveAs(`${S}/e2e/${name}`); return `${S}/e2e/${name}`; };
const docx = await get("#exportWord", "out.docx");
const txt = await get("#exportTxt", "out.txt");
await page.click("#copyAll"); await page.click(".dialog button[type=submit]");
const clip = await page.evaluate(() => navigator.clipboard.readText());
await page.check("#plainPunct");
const txtPlain = await get("#exportTxt", "out-plain.txt");
fs.writeFileSync(`${S}/e2e/expect.json`, JSON.stringify(TRUTH));
check("TXT has both pages", fs.readFileSync(txt, "utf8").split("\n\n").length === 2);
check("TXT keeps Hebrew marks", fs.readFileSync(txt, "utf8").includes("ד״ר"));
check("keyboard punctuation option", fs.readFileSync(txtPlain, "utf8").includes('ד"ר') && !fs.readFileSync(txtPlain, "utf8").includes("״"));
check("Copy = TXT", clip === fs.readFileSync(txt, "utf8"));
check("no page errors", errors.length === 0, errors.join("\n"));
await browser.close();
console.log("DOCX " + docx);
process.exit(done() ? 0 : 1);
